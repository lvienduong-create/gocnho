import { initializeTestEnvironment, assertSucceeds, assertFails } from "@firebase/rules-unit-testing";
import { readFileSync } from "fs";
import { doc, setDoc, getDoc, deleteDoc, collection, getDocs } from "firebase/firestore";
const env = await initializeTestEnvironment({ projectId: "demo-sk", firestore: { rules: readFileSync("../firestore.rules", "utf8"), host: "127.0.0.1", port: 8085 } });
await env.withSecurityRulesDisabled(async c => {
  const d = c.firestore();
  await setDoc(doc(d, "users/mc"), { role: "control" });
  await setDoc(doc(d, "users/j1"), { role: "judge", seat: 1 });
  await setDoc(doc(d, "users/j2"), { role: "judge", seat: 2 });
  await setDoc(doc(d, "users/scr"), { role: "viewer" });
  await setDoc(doc(d, "users/adm"), { role: "admin" });
  await setDoc(doc(d, "game/state"), { status: "open", turnKey: "T1" });
  await setDoc(doc(d, "setup/roster"), { teams: [] });
  await setDoc(doc(d, "votes/T1_j2"), { turnKey: "T1", seat: 2, vote: "pass", at: 1 });
});
const as = (uid, email) => env.authenticatedContext(uid, { email: email || uid + "@x.com" }).firestore();
const owner = as("own", "votu.quynh@sbifpt.com"), mc = as("mc"), j1 = as("j1"), scr = as("scr"), adm = as("adm"), rnd = as("rnd"), anon = env.unauthenticatedContext().firestore();
const T = async (name, p) => { try { await p; console.log("OK  ", name) } catch (e) { console.log("FAIL", name, e.message.slice(0, 120)) } };
await T("anon cannot read roster", assertFails(getDoc(doc(anon, "setup/roster"))));
await T("random signed-in cannot read roster", assertFails(getDoc(doc(rnd, "setup/roster"))));
await T("random cannot make self admin", assertFails(setDoc(doc(rnd, "users/rnd"), { role: "admin" })));
await T("judge reads roster", assertSucceeds(getDoc(doc(j1, "setup/roster"))));
await T("judge cannot write roster", assertFails(setDoc(doc(j1, "setup/roster"), { teams: [] })));
await T("judge cannot write state", assertFails(setDoc(doc(j1, "game/state"), { status: "idle" })));
await T("judge cannot write results", assertFails(setDoc(doc(j1, "results/x"), { points: 1 })));
await T("judge votes own seat", assertSucceeds(setDoc(doc(j1, "votes/T1_j1"), { turnKey: "T1", seat: 1, vote: "pass", at: 1 })));
await T("judge changes own vote", assertSucceeds(setDoc(doc(j1, "votes/T1_j1"), { turnKey: "T1", seat: 1, vote: "fail", at: 2 })));
await T("judge cannot vote other seat", assertFails(setDoc(doc(j1, "votes/T1_j2"), { turnKey: "T1", seat: 2, vote: "pass", at: 1 })));
await T("judge cannot fake seat in id", assertFails(setDoc(doc(j1, "votes/T1_j3"), { turnKey: "T1", seat: 1, vote: "pass", at: 1 })));
await T("judge cannot vote closed/other turn", assertFails(setDoc(doc(j1, "votes/T0_j1"), { turnKey: "T0", seat: 1, vote: "pass", at: 1 })));
await T("judge cannot read other vote", assertFails(getDoc(doc(j1, "votes/T1_j2"))));
await T("judge reads own (missing) vote", assertSucceeds(getDoc(doc(j1, "votes/T9_j1"))));
await T("judge cannot list votes", assertFails(getDocs(collection(j1, "votes"))));
await T("judge cannot delete vote", assertFails(deleteDoc(doc(j1, "votes/T1_j1"))));
await T("judge reads own profile", assertSucceeds(getDoc(doc(j1, "users/j1"))));
await T("judge cannot read others profile", assertFails(getDoc(doc(j1, "users/mc"))));
await T("viewer lists votes", assertSucceeds(getDocs(collection(scr, "votes"))));
await T("viewer cannot write state", assertFails(setDoc(doc(scr, "game/state"), { status: "idle" })));
await T("mc writes state", assertSucceeds(setDoc(doc(mc, "game/state"), { status: "open", turnKey: "T1" })));
await T("mc writes absent", assertSucceeds(setDoc(doc(mc, "game/absent"), { a: "excused" })));
await T("mc writes results", assertSucceeds(setDoc(doc(mc, "results/x"), { points: 1 })));
await T("mc cannot write roster", assertFails(setDoc(doc(mc, "setup/roster"), { teams: [] })));
await T("mc cannot edit users", assertFails(setDoc(doc(mc, "users/mc"), { role: "admin" })));
await T("mc cannot vote", assertFails(setDoc(doc(mc, "votes/T1_j1"), { turnKey: "T1", seat: 1, vote: "pass", at: 1 })));
await T("mc deletes vote", assertSucceeds(deleteDoc(doc(mc, "votes/T1_j2"))));
await T("admin writes roster", assertSucceeds(setDoc(doc(adm, "setup/roster"), { teams: [] })));
await T("admin edits users", assertSucceeds(setDoc(doc(adm, "users/j1"), { role: "judge", seat: 1 })));
await T("owner (no profile) writes users", assertSucceeds(setDoc(doc(owner, "users/new"), { role: "judge", seat: 3 })));
await T("owner lists users", assertSucceeds(getDocs(collection(owner, "users"))));
await T("owner reads own missing profile", assertSucceeds(getDoc(doc(owner, "users/own"))));
await env.cleanup();
